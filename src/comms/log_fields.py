"""
Curated catalog of every loggable variable in the USV system.

Each field describes:
  - id     : stable snake_case identifier (used in CsvLoggerConfig.fields)
  - label  : human-readable label for the GUI
  - topic  : ZMQ topic that carries the source payload (Topics enum value)
  - path   : dot-path inside the payload dict (e.g. "lat", "config.cruise_speed_kn")
  - unit   : display unit
  - dtype  : "float" | "int" | "str" | "bool"

The catalog is grouped for UI display. Group order is preserved.

The field id ``timestamp_utc`` is special: it is always prepended as the first
CSV column / first JSON key and is generated by LoggerProcess itself (ISO-8601
with milliseconds, UTC), so it never appears in this catalog.
"""

