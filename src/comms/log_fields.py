def _index_by_id():
    out = {}
    for g in LOG_FIELD_GROUPS:
        for f in g["fields"]:
            out[f["id"]] = f
    return out


FIELD_INDEX = _index_by_id()
ALL_TOPICS = sorted({f["topic"] for g in LOG_FIELD_GROUPS for f in g["fields"]})


def resolve_path(payload, path):
    """Return the nested value at dot-path inside payload, or None if missing."""
    if payload is None or not path:
        return None
    cur = payload
    for key in path.split("."):
        if isinstance(cur, dict):
            cur = cur.get(key)
        else:
            return None
        if cur is None:
            return None
    return cur
